// Синтез ответа get_quantity_nomenclature (остатки в журнал не сохраняются).
// Структура — по схемам NomCnt/NomStrCnt из src/types/ExportSchemes.ts:
//   response.Остаток.ОстатокПоСтруктурнымЕдиницам[] →
//     Номенклатура.GUIDНоменклатуры        → NOM_ID (рекурсивный поиск в журнале)
//     Номенклатура.НаименованиеНоменклатуры → PACK_NAME (обязателен)
//     СтруктурнаяЕдиница.GUIDСтруктурнойЕдиницы → STR_ID (рекурсивный импорт Storage)
//     ОстатокНаСтруктурнойЕдинице / РезервНаСтруктурнойЕдинице / ЦенаНоменклатуры
export function buildStockResponse({ guid, nomName, storage, cnt, res, price }) {
  return {
    response: {
      Остаток: {
        ОстатокПоСтруктурнымЕдиницам: [
          {
            Номенклатура: {
              GUIDНоменклатуры: guid,
              НаименованиеНоменклатуры: nomName,
            },
            СтруктурнаяЕдиница: {
              GUIDСтруктурнойЕдиницы: storage.guid,
              НаименованиеСтруктурнойЕдиницы: storage.name,
            },
            ОстатокНаСтруктурнойЕдинице: cnt,
            РезервНаСтруктурнойЕдинице: res,
            ЦенаНоменклатуры: price,
          },
        ],
      },
    },
  };
}
